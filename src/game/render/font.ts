export const FONT_H = 7

export function measureText(text: string, spacing = 1) {
  let w = 0
  for (const ch of text.toUpperCase()) w += (G[ch] ?? G['?'])[0].length + spacing
  return Math.max(0, w - spacing)
}

/** Paints text pixel-by-pixel with an optional 1px drop shadow. */
export function drawPixelText(
  ctx: CanvasRenderingContext2D,
  text: string,
  x: number,
  y: number,
  color: string,
  shadow?: string,
  spacing = 1,
) {
  const paint = (ox: number, oy: number, col: string) => {
    ctx.fillStyle = col
    let cx = x + ox
    for (const ch of text.toUpperCase()) {
      const g = G[ch] ?? G['?']
      for (let r = 0; r < g.length; r++)
        for (let c = 0; c < g[r].length; c++) if (g[r][c] === '#') ctx.fillRect(cx + c, y + oy + r, 1, 1)
      cx += g[0].length + spacing
    }
  }
  if (shadow) paint(1, 1, shadow)
  paint(0, 0, color)
}
